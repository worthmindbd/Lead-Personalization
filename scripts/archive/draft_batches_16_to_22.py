def word_count(text: str) -> int:
    return len(re.findall(r"\b\w+\b", text))


def qa(subject: str, body: str) -> list[str]:
    issues = []
    wc = word_count(body)
    if wc > 100:
        issues.append(f"words={wc}")
    if len(subject) > 60:
        issues.append(f"subj={len(subject)}")
    low = (subject + body).lower()
    for b in BANNED:
        if b in low:
            issues.append(b)
    if "calendly" in low or "book 15" in low:
        issues.append("hard CTA")
    return issues


def main():
    by_batch: dict[int, list[dict]] = {b: [] for b in BATCH_RANGES}
    copy_by_batch: dict[int, dict[str, list]] = {b: {} for b in BATCH_RANGES}

    seen_emails: set[str] = set()

    for e in ENTRIES:
        (
            idx, fn, ln, title, company, email, website, linkedin, twitter, fb,
            city, state, signal, notes,
            s1, b1, s2, b2, s3, b3,
        ) = e

        # find which batch this idx belongs to
        batch = None
        for b, (lo, hi) in BATCH_RANGES.items():
            if lo <= idx <= hi:
                batch = b
                break
        if batch is None:
            raise SystemExit(f"csv_index {idx} not in any batch range")

        # de-dupe email guard
        key = email.lower()
        if key in seen_emails:
            raise SystemExit(f"duplicate email in ENTRIES: {email}")
        seen_emails.add(key)

        research = {
            "csv_index": idx,
            "row": idx + 1,
            "first_name": fn,
            "last_name": ln,
            "title": title,
            "company": company,
            "email": email,
            "website": website,
            "linkedin": linkedin,
            "twitter": twitter,
            "facebook": fb,
            "city": city,
            "state": state,
            "research_signal": signal,
            "research_notes": notes,
        }
        by_batch[batch].append(research)

        for subj, body in [(s1, b1), (s2, b2), (s3, b3)]:
            issues = qa(subj, body)
            if issues:
                raise SystemExit(f"QA FAIL idx={idx} subj={subj!r} issues={issues}")
        copy_by_batch[batch][key] = [[s1, b1], [s2, b2], [s3, b3]]

    # write files
    out_summary = []
    for batch, leads in by_batch.items():
        lo, hi = BATCH_RANGES[batch]
        expected = hi - lo + 1
        if len(leads) != expected:
            raise SystemExit(
                f"Batch {batch}: have {len(leads)} leads, expected {expected} "
                f"(indices {lo}-{hi}). Missing or extra."
            )
        r_path = ROOT / "campaigns" / f"pilot-20-batch{batch}-research.json"
        c_path = ROOT / "campaigns" / f"pilot-20-batch{batch}-copy.json"
        r_path.write_text(json.dumps(leads, indent=2) + "\n", encoding="utf-8")
        c_path.write_text(json.dumps(copy_by_batch[batch], indent=2) + "\n", encoding="utf-8")
        out_summary.append(f"batch {batch}: {len(leads)} leads (idx {lo}-{hi}), 60+ emails QA pre-pass")

    print("\n".join(out_summary))
    print(f"Total entries: {len(ENTRIES)} across batches 16-22")


if __name__ == "__main__":
    main()
